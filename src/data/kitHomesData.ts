export interface KitHomeModel {
  id: string;
  officialNumber: number;            // 1 to 20 official register index
  name: string;
  code: string;
  typeLabel: string;                 // e.g. '1 Bedroom / Studio', '2 Bedroom', '3 Bedroom / Highset', etc.
  category: '1-bedroom' | '2-bedroom' | '3-bedroom' | '4-bedroom';
  collectionId: 'collection-a' | 'collection-b' | 'collection-c' | 'collection-d' | 'collection-e';
  collectionName: string;
  collectionEssence: string;
  bedrooms: number;
  bathrooms: number;
  buildingAreaSqm: number;
  dimensions: string;
  stories: number;
  isHighset?: boolean;
  tagline: string;
  designEssence: string;             // Official design essence from Techtural Register RevB
  description: string;
  features: string[];
  inclusions: string[];
  image: string;
  floorPlanImage: string;
  
  // Pricing Breakdown (in PGK - PNG Kina)
  blueprintPrice: number;            // Blueprint PDF Pack rate (K750 for M1–M10, K900 for M11–M14, K1,400 for M15–M20)
  constructionDrawingsPrice?: number;// Complete Construction Drawings & Design rate (K1,700 for M1–M10, K1,900 for M11–M14, K2,100 for M15–M20)
  boqBomPrice: number;               // Optional Complete BOQ & Material Listing Copy rate (K800 for M1–M10, K900 for M11–M14, K950 for M15–M20)
  projectManagementFee: number;      // Project Management Fee
  materialProcurementFee: number;    // Material Procurement & Logistics Fee
  kitMaterialBasePrice: number;      // Base Kitset Structural & Material Package
  fullTurnKeyPrice: number;          // Full Turn-Key Design & Construction Price (K2,700/m² for M1–M10, K3,200/m² for M11–M20)
  isTurnKeyCostingInProgress?: boolean; // When true, turn-key handover price is labeled as "Costing in Progress"
  turnKeyPriceLabel?: string;         // e.g. "Costing in Progress"
  contingencyFee?: number;           // Optional Construction & Site Contingency Fee
  
  // Optional add-ons pricing
  addOns?: {
    solarKitPrice?: number;
    rainwaterSystemPrice?: number;
    cycloneFoundationUpgradePrice?: number;
    contingencyPrice?: number;
  };
}

